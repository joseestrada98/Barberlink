create or replace function public.expire_pending_appointments()
returns integer
language plpgsql
security definer
set search_path = ''
as $$
declare
  changed_count integer;
begin
  update public.appointments a
  set status = 'rejected',
      rejection_reason = 'sin respuesta a tiempo',
      responded_at = now()
  from public.barber_settings s
  where s.id = 1
    and a.status = 'pending'
    and greatest(
      a.expires_at,
      a.created_at + make_interval(secs => s.response_timeout_seconds)
    ) <= clock_timestamp();
  get diagnostics changed_count = row_count;
  return changed_count;
end;
$$;

