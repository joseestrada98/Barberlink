create or replace function public.public_available_slots(requested_date date)
returns table (available_time time)
language plpgsql
security definer
set search_path = ''
as $$
declare
  settings public.barber_settings%rowtype;
  hours public.work_hours%rowtype;
  local_now timestamp;
  slot_time time;
  slot_start timestamptz;
  slot_end timestamptz;
begin
  perform public.expire_pending_appointments();
  select * into settings from public.barber_settings where id = 1;
  if not found or not settings.is_open or requested_date < (now() at time zone 'America/Bogota')::date then
    return;
  end if;
  select * into hours from public.work_hours where weekday = extract(dow from requested_date)::smallint and is_working;
  if not found then return; end if;
  local_now := now() at time zone 'America/Bogota';
  slot_time := hours.opens_at;
  while slot_time + make_interval(mins => settings.slot_minutes) <= hours.closes_at loop
    slot_start := (requested_date + slot_time) at time zone 'America/Bogota';
    slot_end := (requested_date + slot_time + make_interval(mins => settings.slot_minutes)) at time zone 'America/Bogota';
    if (requested_date > local_now::date or slot_start > now())
       and not exists (
         select 1 from public.appointments a
         where a.status in ('pending', 'accepted')
           and (a.appointment_date + a.appointment_time) < (requested_date + slot_time + make_interval(mins => settings.slot_minutes))
           and (a.appointment_date + a.appointment_time + make_interval(mins => settings.slot_minutes)) > (requested_date + slot_time)
       )
       and not exists (
         select 1 from public.blocked_slots b
         where b.starts_at < slot_end and b.ends_at > slot_start
       )
    then
      available_time := slot_time;
      return next;
    end if;
    slot_time := slot_time + make_interval(mins => settings.slot_minutes);
  end loop;
end;
$$;

create or replace function public.request_appointment(
  customer_name text,
  customer_phone text,
  requested_date date,
  requested_time time,
  payment_method text
)
returns table (access_token text, expires_at timestamptz)
language plpgsql
security definer
set search_path = ''
as $$
declare
  settings public.barber_settings%rowtype;
  expiry timestamptz;
  normalized_phone text;
  pending_count integer;
begin
  perform public.expire_pending_appointments();
  select * into settings from public.barber_settings where id = 1 for update;
  if not found or not settings.is_open then
    raise exception 'La agenda está cerrada y no recibe nuevas solicitudes.';
  end if;
  if customer_name is null or char_length(trim(customer_name)) not between 1 and 80 then
    raise exception 'Escribe un nombre de hasta 80 caracteres.';
  end if;
  normalized_phone := regexp_replace(trim(customer_phone), '[^0-9+]', '', 'g');
  if customer_phone is null or char_length(normalized_phone) not between 7 and 20 then
    raise exception 'Escribe un número de teléfono válido.';
  end if;
  if payment_method is null or payment_method not in ('cash', 'transfer') then
    raise exception 'Selecciona un método de pago válido.';
  end if;
  if requested_date < (now() at time zone 'America/Bogota')::date then
    raise exception 'Selecciona una fecha futura.';
  end if;

  perform pg_advisory_xact_lock(hashtextextended(requested_date::text || requested_time::text, 0));
  if not exists (
    select 1 from public.public_available_slots(requested_date) s where s.available_time = requested_time
  ) then
    raise exception 'Ese horario ya no está disponible. Actualiza la lista y elige otra hora.';
  end if;
  select count(*) into pending_count from public.appointments
  where customer_phone = normalized_phone and status = 'pending';
  if pending_count >= settings.max_pending_per_phone then
    raise exception 'Ya tienes el máximo de solicitudes pendientes para este teléfono.';
  end if;
  expiry := now() + make_interval(secs => settings.response_timeout_seconds);
  insert into public.appointments (access_token, customer_name, customer_phone, appointment_date, appointment_time, payment_method, expires_at)
  values (replace(pg_catalog.gen_random_uuid()::text, '-', '') || replace(pg_catalog.gen_random_uuid()::text, '-', ''), trim(customer_name), normalized_phone, requested_date, requested_time, payment_method, expiry)
  returning public.appointments.access_token, public.appointments.expires_at into access_token, expires_at;
  return next;
end;
$$;

create or replace function public.public_appointment_by_token(token text)
returns table (
  customer_name text,
  appointment_date date,
  appointment_time time,
  payment_method text,
  status text,
  rejection_reason text,
  expires_at timestamptz,
  delay_minutes integer
)
language plpgsql
security definer
set search_path = ''
as $$
begin
  perform public.expire_pending_appointments();
  return query
    select a.customer_name, a.appointment_date, a.appointment_time, a.payment_method, a.status, a.rejection_reason, a.expires_at, a.delay_minutes
    from public.appointments a
    where a.access_token = token and char_length(token) in (64, 72);
end;
$$;

create or replace function public.cancel_appointment(token text)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
  affected integer;
begin
  update public.appointments
  set status = 'cancelled', responded_at = now()
  where access_token = token and char_length(token) in (64, 72) and status in ('pending', 'accepted');
  get diagnostics affected = row_count;
  if affected = 0 then raise exception 'Esta cita ya no se puede cancelar.'; end if;
  return true;
end;
$$;

create or replace function public.respond_to_appointment(appointment_id uuid, accept_request boolean)
returns text
language plpgsql
security definer
set search_path = ''
as $$
declare
  current_status text;
  current_expiry timestamptz;
  current_created_at timestamptz;
  current_response_timeout integer;
  next_status text;
begin
  if not public.is_barber() then raise exception 'Debes iniciar sesión como barbero.'; end if;
  select a.status, a.expires_at, a.created_at, coalesce(s.response_timeout_seconds, 600)
    into current_status, current_expiry, current_created_at, current_response_timeout
  from public.appointments a
  left join public.barber_settings s on s.id = 1
  where a.id = appointment_id
  for update of a;
  if not found or current_status <> 'pending' then
    raise exception 'La solicitud ya fue atendida o expiró.';
  end if;
  if greatest(
    current_expiry,
    current_created_at + make_interval(secs => current_response_timeout)
  ) <= clock_timestamp() then
    update public.appointments set status = 'rejected', rejection_reason = 'sin respuesta a tiempo', responded_at = now()
    where id = appointment_id and status = 'pending';
    return 'expired';
  end if;
  next_status := case when accept_request then 'accepted' else 'rejected' end;
  update public.appointments set status = next_status, responded_at = now()
  where id = appointment_id and status = 'pending';
  return next_status;
end;
$$;

