-- Una respuesta de 15 segundos no puede programarse con precisión desde pg_cron,
-- que ejecuta por minuto. Las consultas y las respuestas del panel expiran al instante;
-- este proceso de respaldo actualiza el estado incluso en periodos sin visitas.
do $$
begin
  if exists (select 1 from cron.job where jobname = 'expire-barber-pending-appointments') then
    perform cron.unschedule('expire-barber-pending-appointments');
  end if;
  perform cron.schedule(
    'expire-barber-pending-appointments',
    '* * * * *',
    'select public.expire_pending_appointments()'
  );
end;
$$;

